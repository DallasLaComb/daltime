#!/usr/bin/env node
/**
 * Writes frontend/.env.mobile.<env> from the deployed CloudFormation stacks, using the same
 * outputs cd.yml reads. Requires the AWS CLI and an active SSO session (docs/aws-login.md).
 *
 *   node scripts/mobile-env-pull.mjs <dev|qa|main>
 *
 * The values are not secret (they already ship inside the public web bundle) but the file is
 * git-ignored to keep the pattern.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ENVIRONMENTS, frontendDir } from './mobile-env.mjs';

// cd.yml: foundation stack = daltime-foundation-<branch>; backend stack = vars.SAM_STACK_NAME
const TARGETS = {
  dev: { profile: 'daltime-dev', foundation: 'daltime-foundation-dev', backend: 'daltime-backend-dev' },
  qa: { profile: 'daltime-qa', foundation: 'daltime-foundation-qa', backend: 'daltime-backend-qa' },
  main: { profile: 'daltime-prod', foundation: 'daltime-foundation-main', backend: 'daltime-backend-prod' },
};

function stackOutputs(stackName, profile) {
  const json = execFileSync(
    'aws',
    [
      'cloudformation', 'describe-stacks',
      '--stack-name', stackName,
      '--region', 'us-east-1',
      '--profile', profile,
      '--query', 'Stacks[0].Outputs',
      '--output', 'json',
    ],
    { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] },
  );
  return Object.fromEntries(JSON.parse(json).map((o) => [o.OutputKey, o.OutputValue]));
}

function required(outputs, key, stack) {
  if (!outputs[key]) throw new Error(`Output "${key}" not found on stack ${stack}`);
  return outputs[key];
}

const env = process.argv[2];
if (!ENVIRONMENTS.includes(env)) {
  console.error(`Usage: node scripts/mobile-env-pull.mjs <${ENVIRONMENTS.join('|')}>`);
  process.exit(1);
}

try {
  const { profile, foundation, backend } = TARGETS[env];
  const f = stackOutputs(foundation, profile);
  const b = stackOutputs(backend, profile);
  const lines = [
    `# Generated by scripts/mobile-env-pull.mjs for "${env}" — git-ignored.`,
    `API_BASE_URL=${required(b, 'ApiEndpoint', backend)}`,
    `COGNITO_USER_POOL_ID=${required(f, 'UserPoolId', foundation)}`,
    `COGNITO_CLIENT_ID=${required(f, 'UserPoolClientId', foundation)}`,
    `COGNITO_REGION=${required(f, 'CognitoRegion', foundation)}`,
    `COGNITO_DOMAIN=${required(f, 'CognitoDomain', foundation)}`,
    '',
  ];
  const target = join(frontendDir, `.env.mobile.${env}`);
  writeFileSync(target, lines.join('\n'));
  console.log(`✓ Wrote ${target}`);
} catch (err) {
  const detail = err && typeof err === 'object' && 'stderr' in err ? String(err.stderr).trim() : '';
  console.error(`✖ ${err instanceof Error ? err.message : err}${detail ? `\n${detail}` : ''}`);
  console.error('  Is your SSO session active? Run: aws sso login --sso-session daltime');
  process.exit(1);
}
